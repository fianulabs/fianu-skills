#!/usr/bin/env bash
# Vendors the Terraform provider's generated docs into
# skills/deploying-entities-terraform/references/provider-docs/.
#
#   ./scripts/sync-provider-docs.sh [--check] [path-to-provider-repo]
#
# Provider repo location resolves in this order:
#   1. $1
#   2. $FIANU_TF_PROVIDER_REPO
#   3. ../terraform-provider-fianu (sibling checkout)
#
# Docs are read from the newest RELEASE TAG, never from the working tree — a
# stale local checkout is exactly the failure this script exists to prevent.
# `git fetch --tags` runs first; if it fails (offline), the local tag list is
# used and a warning is printed.
#
# Upstream docs are themselves generated by tfplugindocs from the live provider
# schemas (see the provider's generate.go), and tfplugindocs inlines
# examples/resources/*/resource.tf into each page's Example Usage block — so
# vendoring docs/ carries the worked examples along with the schemas.
#
# --check re-extracts to a temp dir and diffs; non-zero exit means the vendored
# copy has drifted from the newest tag (or someone hand-edited it).
set -euo pipefail

CHECK=0
if [ "${1:-}" = "--check" ]; then
    CHECK=1
    shift
fi

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PROVIDER="${1:-${FIANU_TF_PROVIDER_REPO:-$REPO_ROOT/../terraform-provider-fianu}}"
SHIPPED="$REPO_ROOT/skills/deploying-entities-terraform/references/provider-docs"

if [ ! -e "$PROVIDER/.git" ]; then
    echo "FAIL: provider repo not found at $PROVIDER" >&2
    echo "      pass the repo path as \$1 or set FIANU_TF_PROVIDER_REPO" >&2
    exit 1
fi

if ! git -C "$PROVIDER" fetch --tags --quiet 2>/dev/null; then
    echo "WARN: could not fetch tags from $PROVIDER; using the local tag list" >&2
fi

TAG="$(git -C "$PROVIDER" tag --list 'v*' --sort=-v:refname | head -1)"
if [ -z "$TAG" ]; then
    echo "FAIL: no v* tags in $PROVIDER" >&2
    exit 1
fi
SHA="$(git -C "$PROVIDER" rev-parse --short "$TAG")"

DEST="$SHIPPED"
if [ "$CHECK" -eq 1 ]; then
    DEST="$(mktemp -d)"
    trap 'rm -rf "$DEST"' EXIT
fi

# Recreate from scratch so docs deleted upstream do not linger here.
rm -rf "$DEST"
mkdir -p "$DEST"
git -C "$PROVIDER" archive "$TAG" docs/ | tar -x -C "$DEST" --strip-components=1

{
    echo "# Terraform provider docs (vendored)"
    echo
    echo "VENDORED — do not hand-edit. Re-sync with \`./scripts/sync-provider-docs.sh\`."
    echo
    echo "Source: \`fianulabs/terraform-provider-fianu\` at \`$TAG\` (\`$SHA\`)"
    echo
    echo "Generated upstream by \`tfplugindocs\` from the live provider schemas, so"
    echo "these pages are the authoritative HCL contract — including every nested"
    echo "attribute and a worked \`Example Usage\` block per resource."
    echo
    echo "Read the page for the resource you are authoring. Do not read them all."
    echo
    echo "| Page | Covers |"
    echo "|---|---|"
    echo "| \`index.md\` | Provider block: auth attributes and endpoint configuration. |"
    for f in "$DEST"/resources/*.md; do
        [ -e "$f" ] || continue
        n="$(basename "$f" .md)"
        echo "| \`resources/$n.md\` | \`fianu_$n\` resource schema. |"
    done
    for f in "$DEST"/actions/*.md; do
        [ -e "$f" ] || continue
        n="$(basename "$f" .md)"
        echo "| \`actions/$n.md\` | \`fianu_$n\` action schema. |"
    done

# README.md, NOT INDEX.md — macOS APFS is case-insensitive by default, so
# INDEX.md and the provider's own docs/index.md are the same path and one
# silently clobbers the other.
} > "$DEST/README.md"

if [ "$CHECK" -eq 1 ]; then
    if diff -ru "$SHIPPED" "$DEST"; then
        echo "sync-provider-docs --check: OK ($TAG)"
    else
        echo "FAIL: provider-docs have drifted from $TAG; run ./scripts/sync-provider-docs.sh" >&2
        exit 1
    fi
else
    echo "synced $SHIPPED from $TAG ($SHA), $(find "$DEST" -name '*.md' | wc -l | tr -d ' ') files"
fi
